def teacher_desc(style: str, dialect: str, personality: str, detail: str, subject: str) -> str:
    """按请求参数拼出教师人格描述。"""
    parts = []
    if style == "dialect":
        parts.append(STYLE_DESC["dialect"].format(dialect=dialect))
    elif style in STYLE_DESC:
        parts.append(STYLE_DESC[style])
    else:
        parts.append("一位经验丰富的中学教师")

    if personality:
        desc = PERSONALITY_DESC.get(personality.upper())
        if desc:
            parts.append(f"你的 teaching 风格偏 {desc}")

    d = DETAIL_DESC.get(detail, "")
    if d:
        parts.append(f"本次回答{d}")

    if subject and subject not in ("未知", ""):
        parts.append(f"你熟悉{subject}学科")

    return "，".join(parts)


